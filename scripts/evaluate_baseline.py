"""Reproducible baseline + evaluation report.   python -m scripts.evaluate_baseline

Model: TF-IDF (character 2-5-grams + word 1-2-grams) -> logistic regression. This is a PIPELINE-VERIFICATION baseline, not the final model.
Leakage / imbalance rules enforced here:
  * the vectorizer, the class weights and the model are fitted on train.csv ONLY;
  * the decision threshold is chosen on validation.csv ONLY and then frozen;
  * test.csv, test_hindi.csv, test_hinglish.csv and the benchmark are used once, for reporting;
  * imbalance is handled by class weights computed from the training labels (no resampling, so no duplicate leaks into validation/test).
Metrics (scam = positive class): precision, recall, F1, PR-AUC (average precision), ROC-AUC, confusion matrix; bootstrap 95% CI on small sets.
"""
import hashlib, json, sys
from pathlib import Path
import numpy as np, pandas as pd
from scipy.sparse import hstack
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, confusion_matrix, f1_score, precision_recall_curve, precision_score, recall_score, roc_auc_score

SEED = 42
P = Path("data/processed")
SETS = {"validation": "validation.csv", "test (main, mostly English)": "test.csv", "test_hindi": "test_hindi.csv",
        "test_hinglish": "test_hinglish.csv", "benchmark (45, curated)": "heldout_benchmark_candidates.csv"}


def load(name):
    d = pd.read_csv(P / name, keep_default_na=False)
    d = d[d.final_label.isin(["scam", "legitimate"])].copy()
    d["y"] = (d.final_label == "scam").astype(int)
    return d


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()[:16]


def metrics(y, p, thr):
    pred = (p >= thr).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return dict(n=len(y), scams=int(y.sum()), precision=precision_score(y, pred, zero_division=0), recall=recall_score(y, pred, zero_division=0),
                f1=f1_score(y, pred, zero_division=0), pr_auc=average_precision_score(y, p) if 0 < y.sum() < len(y) else float("nan"),
                roc_auc=roc_auc_score(y, p) if 0 < y.sum() < len(y) else float("nan"), tn=int(tn), fp=int(fp), fn=int(fn), tp=int(tp),
                accuracy=(tn + tp) / len(y), majority_accuracy=1 - y.mean())


def boot_ci(y, p, thr, reps=500):
    rng = np.random.RandomState(SEED); f, a = [], []
    for _ in range(reps):
        i = rng.randint(0, len(y), len(y)); yy, pp = y[i], p[i]
        if yy.sum() == 0 or yy.sum() == len(yy): continue
        f.append(f1_score(yy, (pp >= thr).astype(int), zero_division=0)); a.append(average_precision_score(yy, pp))
    return (np.percentile(f, [2.5, 97.5]) if f else (np.nan, np.nan)), (np.percentile(a, [2.5, 97.5]) if a else (np.nan, np.nan))


def main():
    tr = load("train.csv")
    n0, n1 = (tr.y == 0).sum(), (tr.y == 1).sum()
    cw = {0: len(tr) / (2 * n0), 1: len(tr) / (2 * n1)}                      # class weights from TRAINING labels only
    ch = TfidfVectorizer(analyzer="char_wb", ngram_range=(2, 5), min_df=3, max_features=300_000, sublinear_tf=True, lowercase=True)
    wd = TfidfVectorizer(analyzer="word", ngram_range=(1, 2), min_df=2, max_features=150_000, sublinear_tf=True, lowercase=True, token_pattern=r"(?u)\b\w+\b")
    Xtr = hstack([ch.fit_transform(tr.message), wd.fit_transform(tr.message)]).tocsr()
    model = LogisticRegression(C=4.0, class_weight=cw, solver="liblinear", max_iter=200, random_state=SEED).fit(Xtr, tr.y)
    feat = lambda d: hstack([ch.transform(d.message), wd.transform(d.message)]).tocsr()

    va = load("validation.csv"); pv = model.predict_proba(feat(va))[:, 1]
    prec, rec, th = precision_recall_curve(va.y, pv)
    f1s = 2 * prec[:-1] * rec[:-1] / np.clip(prec[:-1] + rec[:-1], 1e-9, None)
    thr_f1 = float(th[int(np.argmax(f1s))])                                   # F1-optimal threshold, chosen on validation
    ok = np.where(prec[:-1] >= 0.95)[0]
    thr_p95 = float(th[ok[np.argmax(rec[:-1][ok])]]) if len(ok) else thr_f1   # highest recall with precision >= 95% on validation
    results, rows = {}, []
    md = ["# Baseline model evaluation report (auto-generated by scripts/evaluate_baseline.py)\n",
          "**Read first.** Labels are automatic (rules + Claude's reading, label policy v2), **not** independently human-verified. `test_hindi` / `test_hinglish` "
          "come from LLM-generated Dataset D and are awaiting independent review; the 45-message benchmark is too small for stable estimates. "
          "This is a pipeline-verification baseline, not a final model. Do not quote these numbers as real-world performance.\n",
          f"## Training setup\n- train: {len(tr)} messages ({int(n1)} scam = {n1/len(tr):.1%}, {int(n0)} legitimate); class weights from train only: legitimate {cw[0]:.2f}, scam {cw[1]:.2f}",
          f"- features: char_wb 2-5-grams (<=300k) + word 1-2-grams (<=150k), TF-IDF fitted on train only; logistic regression C=4 (liblinear), seed {SEED}",
          f"- thresholds chosen on validation only: F1-optimal = {thr_f1:.3f}; max-recall at precision>=95% = {thr_p95:.3f}; default = 0.500\n"]
    md.append("## Results (scam = positive class)\n")
    for name, f in SETS.items():
        if not (P / f).exists(): continue
        d = load(f)
        if len(d) == 0 or d.y.nunique() < 2 and name != "validation": pass
        p = model.predict_proba(feat(d))[:, 1]; y = d.y.values
        results[name] = {}
        for tname, thr in [("default 0.5", 0.5), ("F1-opt (val)", thr_f1), ("P>=95% (val)", thr_p95)]:
            m = metrics(y, p, thr); results[name][tname] = m
            rows.append({"set": name, "threshold": tname, **{k: (round(v, 3) if isinstance(v, float) else v) for k, v in m.items() if k in ("n", "scams", "precision", "recall", "f1", "pr_auc", "roc_auc", "accuracy", "majority_accuracy", "tn", "fp", "fn", "tp")}})
        (flo, fhi), (alo, ahi) = boot_ci(y, p, thr_f1)
        results[name]["ci"] = {"f1": [float(flo), float(fhi)], "pr_auc": [float(alo), float(ahi)]}
    tab = pd.DataFrame(rows)
    md.append(tab.to_markdown(index=False)); md.append("")
    md.append("### 95% bootstrap intervals at the validation-chosen F1 threshold (matter most for the small sets)\n")
    md.append(pd.DataFrame([{"set": k, "F1 95% CI": f"{v['ci']['f1'][0]:.2f}-{v['ci']['f1'][1]:.2f}", "PR-AUC 95% CI": f"{v['ci']['pr_auc'][0]:.2f}-{v['ci']['pr_auc'][1]:.2f}"} for k, v in results.items()]).to_markdown(index=False))
    md.append("\n> `majority_accuracy` is the accuracy of predicting 'legitimate' for everything; accuracy alone is not a valid measure here.\n")

    # spam vs fraud recall, by language and by origin, on the main test
    te = load("test.csv"); te["p"] = model.predict_proba(feat(te))[:, 1]; te["pred"] = (te.p >= thr_f1).astype(int)
    sc = te[te.y == 1]
    md.append("## Main test: scam recall by group (F1-optimal threshold)\n")
    md.append(sc.groupby("scam_group").agg(scams=("pred", "size"), recall=("pred", "mean")).round(3).to_markdown())
    md.append("\n" + sc.groupby("scam_category").agg(scams=("pred", "size"), recall=("pred", "mean")).sort_values("scams", ascending=False).head(12).round(3).to_markdown())
    md.append("\n## Main test: by source\n")
    md.append(te.groupby("source").apply(lambda g: pd.Series({"n": len(g), "scams": int(g.y.sum()), "recall": g.loc[g.y == 1, "pred"].mean() if g.y.sum() else np.nan,
              "false_positive_rate": g.loc[g.y == 0, "pred"].mean() if (g.y == 0).sum() else np.nan}), include_groups=False).round(3).to_markdown())
    # hard negatives: genuine notifications / personal messages that look like scams. False-positive rate by kind of legitimate message.
    lg = te[te.y == 0].copy()
    lg["kind"] = np.where(lg.final_method == "rule_legit", lg.final_reason.str.split(":").str[0], np.where(lg.final_method == "source_label", "other (source label)", lg.final_method))
    md.append("\n## Main test: false-positive rate on LEGITIMATE messages by kind (genuine notices are the hard negatives)\n")
    md.append(lg.groupby("kind").agg(n=("pred", "size"), false_positive_rate=("pred", "mean")).sort_values("n", ascending=False).round(3).to_markdown())
    # the Hindi / Hinglish test sets: what a model trained on mostly-English data does
    for nm in ("test_hindi", "test_hinglish"):
        if nm in results:
            m = results[nm]["F1-opt (val)"]
            md.append(f"\n**{nm}:** F1 {m['f1']:.2f}, precision {m['precision']:.2f}, recall {m['recall']:.2f} on {m['n']} messages ({m['scams']} scams); "
                      f"CI width shows how little a set this small can say.")
    # data fingerprints for reproducibility
    md.append("\n## Reproducibility\nSHA-256 (first 16 hex) of the exact files used:\n")
    md.append(pd.DataFrame([{"file": f, "sha256_16": sha256(P / f)} for f in ["train.csv", "validation.csv", "test.csv", "test_hindi.csv", "test_hinglish.csv", "heldout_benchmark_candidates.csv", "final_dataset.csv"] if (P / f).exists()]).to_markdown(index=False))
    md.append("\nRe-run: `python scripts/build_dataset.py && python -m scripts.finalize_dataset && python -m scripts.evaluate_baseline`")
    Path("docs/model_evaluation_report.md").write_text("\n".join(md), encoding="utf-8")
    Path("docs/model_metrics.json").write_text(json.dumps(results, indent=1, default=float), encoding="utf-8")
    print(tab[tab.threshold == "F1-opt (val)"][["set", "n", "scams", "precision", "recall", "f1", "pr_auc", "majority_accuracy"]].to_string(index=False))


if __name__ == "__main__":
    main()
